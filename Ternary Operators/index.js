//Ternary Operators:
//Ternary Operators is used for quick conditional checks....
//it is a short hand of if-else statements..

//If else
const number=75;
if(number>79){
    console.log("Number is greater than 79");
    
}else{
    console.log("Number is less than 79");
    
}


//Ternary 

const number1=75;
console.log(number1>79? "Number is greater than 79":"Number is less than 79");
